//! EN/RU strings — ported from the Svelte frontend's i18n.js dictionary.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    En,
    Ru,
}

impl Lang {
    pub fn toggle(self) -> Lang {
        match self {
            Lang::En => Lang::Ru,
            Lang::Ru => Lang::En,
        }
    }

    pub fn from_str(value: &str) -> Lang {
        match value {
            "ru" => Lang::Ru,
            _ => Lang::En,
        }
    }
}

